"""Transactional invoice ledger for PostgreSQL and the local demo."""

from contextlib import closing, contextmanager
from hashlib import blake2b
from pathlib import Path
import sqlite3


HISTORY = Path(__file__).resolve().parent / "data" / "web-runs.sqlite3"


class PostgresLedger:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, query, parameters=()):
        return self.connection.execute(query.replace("?", "%s"), parameters)


def _create_schema(connection, id_column):
    connection.execute(f"""
        CREATE TABLE IF NOT EXISTS ap_runs (
            id {id_column}, created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            scope TEXT NOT NULL, filename TEXT NOT NULL,
            vendor TEXT NOT NULL, invoice TEXT NOT NULL, po TEXT,
            status TEXT NOT NULL, outcome TEXT NOT NULL, quantities TEXT NOT NULL,
            variance TEXT NOT NULL
        )
    """)
    connection.execute("""
        CREATE UNIQUE INDEX IF NOT EXISTS ap_runs_approved
        ON ap_runs (scope, vendor, invoice) WHERE status = 'Approved'
    """)
    connection.execute("CREATE INDEX IF NOT EXISTS ap_runs_history ON ap_runs (scope, id DESC)")


@contextmanager
def open_ledger(*, db_path=None, database_url=None, scope="", write=False):
    if database_url:
        import psycopg

        # Transaction poolers may assign a different server connection on the next request.
        with psycopg.connect(database_url, connect_timeout=6, prepare_threshold=None) as connection:
            connection.execute("SET LOCAL statement_timeout = '12s'")
            connection.execute("SET LOCAL TIME ZONE 'UTC'")
            connection.execute("SET LOCAL search_path TO invoice_review")
            if connection.execute("SELECT to_regclass('invoice_review.ap_runs')").fetchone()[0] is None:
                connection.execute("SELECT pg_advisory_xact_lock(682206, 1)")
                connection.execute("CREATE SCHEMA IF NOT EXISTS invoice_review")
                _create_schema(connection, "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
            if write:
                lock_id = int.from_bytes(blake2b(scope.encode(), digest_size=8).digest(), "big", signed=True)
                connection.execute("SELECT pg_advisory_xact_lock(%s)", (lock_id,))
            yield PostgresLedger(connection)
        return

    with closing(sqlite3.connect(HISTORY if db_path is None else db_path, timeout=10)) as connection:
        with connection:
            if write:
                connection.execute("BEGIN IMMEDIATE")
            _create_schema(connection, "INTEGER PRIMARY KEY")
            yield connection
