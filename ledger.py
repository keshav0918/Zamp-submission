"""SQLite for local runs and PostgreSQL for the Vercel ledger."""

from contextlib import contextmanager
from hashlib import blake2b
from pathlib import Path
import sqlite3


HISTORY = Path(__file__).resolve().parent / "data" / "web-runs.sqlite3"


class Ledger:
    def __init__(self, connection, postgres):
        self.connection = connection
        self.postgres = postgres

    def execute(self, query, parameters=()):
        if self.postgres:
            query = query.replace("?", "%s")
        return self.connection.execute(query, parameters)


def _create(ledger):
    key = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if ledger.postgres else "INTEGER PRIMARY KEY"
    ledger.execute(f"""
        CREATE TABLE IF NOT EXISTS ap_runs (
            id {key}, created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            scope TEXT NOT NULL, filename TEXT NOT NULL,
            vendor TEXT NOT NULL, invoice TEXT NOT NULL, po TEXT,
            status TEXT NOT NULL, outcome TEXT NOT NULL, quantities TEXT NOT NULL,
            variance TEXT NOT NULL
        )
    """)
    ledger.execute("""
        CREATE UNIQUE INDEX IF NOT EXISTS ap_runs_approved
        ON ap_runs (scope, vendor, invoice) WHERE status = 'Approved'
    """)
    ledger.execute("CREATE INDEX IF NOT EXISTS ap_runs_history ON ap_runs (scope, id DESC)")


@contextmanager
def open_ledger(*, scope, database_url=None, db_path=None, write=False):
    if database_url:
        import psycopg

        connection = psycopg.connect(database_url, connect_timeout=6)
    else:
        connection = sqlite3.connect(HISTORY if db_path is None else db_path, timeout=10)
    try:
        ledger = Ledger(connection, bool(database_url))
        if ledger.postgres:
            if ledger.execute("SELECT to_regclass('ap_runs')").fetchone()[0] is None:
                ledger.execute("SELECT pg_advisory_xact_lock(682206, 1)")
                _create(ledger)
            connection.commit()
        else:
            _create(ledger)
            connection.commit()
        if write:
            if ledger.postgres:
                lock_id = int.from_bytes(blake2b(scope.encode(), digest_size=8).digest(), "big", signed=True)
                ledger.execute("SELECT pg_advisory_xact_lock(?)", (lock_id,))
            else:
                ledger.execute("BEGIN IMMEDIATE")
        yield ledger
        connection.commit()
    except BaseException:
        connection.rollback()
        raise
    finally:
        connection.close()
